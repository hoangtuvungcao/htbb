def chuan_luoi(luoi):
    """Khoảng trắng gõ nhầm trong lưới: giữa dòng -> '2' (thân), cuối dòng -> '3' (bóng)."""
    ra = []
    for dong in luoi.strip("\n").split("\n"):
        goc = dong.rstrip(" ")
        ra.append(goc.replace(" ", "2") + "3" * (len(dong) - len(goc)))
    return "\n".join(ra)


def huy_hieu_gym(i):
    """Huy hiệu Gym bậc i + dải ruy băng màu vùng phía dưới (lưới 14 dòng)."""
    return chuan_luoi(HUY_HIEU_GYM[i]) + "\n....456654....\n....45..54...."


def bang_mau(chat, nhan):
    """Bảng vai màu: chat = rgb24 chất liệu, nhan = rgb24 màu nhấn."""
    c1, c2, c3 = ba_sac(chat)
    n1, n2, n3 = ba_sac(nhan)
    return {
        "1": c1, "2": c2, "3": c3,
        "4": n1, "5": n2, "6": n3,
        "W": sang(c1, 0.7), "k": toi(c3, 0.45), "P": c2,
    }


def vien_cua(chat, nhan):
    return mau_vien(tron(chat, nhan, 0.35))


def dong_huy_hieu(anh, mau_he_idx, x0, y0, chat, nhan):
    """Đóng huy hiệu hệ 5x5 lên mặt khoá: nét màu nhấn đậm, bóng 1 px dưới-phải."""
    mat = HUY_HIEU_HE[mau_he_idx]
    _, n2, n3 = ba_sac(nhan)
    net = toi(n2, 0.05) if (sum((nhan >> s) & 0xFF for s in (16, 8, 0)) < 520) else toi(n2, 0.25)
    bong = toi(chat, 0.45)
    for y in range(5):
        for x in range(5):
            if mat[y][x] == "#":
                X, Y = x0 + x + 1, y0 + y + 1
                if Y + 1 < anh[1] and X + 1 < anh[0] and (y == 4 or mat[y + 1][x] != "#"):
                    anh[2][Y + 1][X] = 0xFF000000 | bong
    for y in range(5):
        for x in range(5):
            if mat[y][x] == "#":
                anh[2][y0 + y + 1][x0 + x + 1] = 0xFF000000 | net
    return anh


def lam_icon(luoi, chat, nhan, huy_hieu=None, toa_do_hh=None, bac=0):
    """Một icon 16x16 hoàn chỉnh: lưới -> viền -> huy hiệu -> lấp lánh theo bậc -> căn giữa."""
    bm = bang_mau(chat, nhan)
    anh = ve_luoi(luoi, bm, vien=vien_cua(chat, nhan))
    if huy_hieu is not None and toa_do_hh is not None:
        dong_huy_hieu(anh, huy_hieu, toa_do_hh[0], toa_do_hh[1], chat, nhan)
    # bậc cao: điểm lấp lánh (bậc 6+ một, bậc 9+ hai, tối thượng có điểm cầu vồng)
    if bac >= 6:
        lap_lanh(anh, 0xFFFFFF, 0)
    if bac >= 9:
        lap_lanh(anh, 0xFFF4A0, 1)
    if bac >= 10:
        lap_lanh(anh, 0xFF80E0, 2)
    ra = anh_moi(16, 16)
    dan(ra, anh, (16 - anh[0]) // 2, (16 - anh[1]) // 2)
    return ra


_DIEM_LAP_LANH = [(0, 0), (1, 1), (0, 1)]


def lap_lanh(anh, mau, thu):
    """Đặt chữ thập lấp lánh 3x3 ở góc trống (trên-phải, dưới-trái, trên-trái theo thứ tự)."""
    w, h, px = anh
    goc = [(w - 2, 1), (1, h - 2), (1, 1)][thu % 3]
    x, y = goc
    for dx, dy in ((0, 0), (1, 0), (-1, 0), (0, 1), (0, -1)):
        X, Y = x + dx, y + dy
        if 0 <= X < w and 0 <= Y < h and px[Y][X] >> 24 == 0:
            px[Y][X] = 0xFF000000 | (mau if (dx, dy) == (0, 0) else sang(mau, 0.0))
