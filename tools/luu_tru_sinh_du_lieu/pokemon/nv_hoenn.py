DOI_Q = {(74, "#130"): "#129", (78, "#120"): ""}

KIEU_CAN_QUAI = ("giet", "giet_tinh_anh", "thu_thap", "quan_sat", "thu_thach_gio", "pokedex_ha", "pokedex_gap")


def quai_tren_map(map_id):
    """Cac id mau quai moc tren ban do (luoi map/map<N>)."""
    f = os.path.join(GOC, "server", "map", "map%d" % map_id)
    if not os.path.isfile(f):
        return []
    b = open(f, "rb").read()
    return sorted(set(x for x in b[2:2 + b[0] * b[1]] if x not in (0, 255)))


def _tach(tss):
    ds = [p for p in tss.split(";") if p.strip()] if tss else []
    return [(p.split("=", 1)[0].strip(), p.split("=", 1)[1] if "=" in p else "") for p in ds]


def _ghep(cap):
    return ";".join("%s=%s" % (k, v) for k, v in cap)


def chuan_buoc(stt, bi, buoc, L, cap_quai):
    """buoc nv_cot_truyen (kieu, tss, ten, mo, xong) -> buoc co map=/diem= va quai Hoenn moc tren ban do.
    cap_quai: id template -> cap (sinh_sql_lau_dai ten_quai_tat_ca)."""
    kieu, tss, ten, mo, xong = buoc
    noi, diem0, rieng = CHUONG[stt]
    cap = _tach(tss)
    d = dict(cap)
    noi_buoc = NOI_CU.get(d.get("noi", ""), noi) if "noi" in d else noi
    if noi_buoc not in DIA_DANH:
        raise ValueError("C%d.%d: dia danh '%s' khong co ban do Hoenn" % (stt, bi, noi_buoc))
    if "map" not in d:
        cap.append(("map", noi_buoc))
    if kieu != "cau_ca" and "diem" not in d:
        cap.append(("diem", str(rieng.get(bi, diem0))))
    q = d.get("q")
    if q is not None and (stt, q) in DOI_Q:
        moi = DOI_Q[(stt, q)]
        cap = [(k, v) for k, v in cap if k != "q"] + ([("q", moi)] if moi else [])
        q = moi or None
    if kieu in KIEU_CAN_QUAI and (q is None or not q.startswith("#")):
        mid = DIA_DANH[noi_buoc]
        ds = quai_tren_map(mid) or quai_tren_map(QUAI_GAN.get(mid, mid))
        if not ds:
            raise ValueError("C%d.%d: ban do %d (va ban do gan) khong co quai" % (stt, bi, mid))
        muc = L + int(q or "+0")
        chon = min(ds, key=lambda i: (abs(cap_quai.get(i, muc) - muc), i))
        cap = [(k, v) for k, v in cap if k != "q"] + [("q", "#%d" % chon)]
    return (kieu, _ghep(cap), ten, mo, xong)


